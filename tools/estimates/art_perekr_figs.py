# ── Рис.8: теплопотери через верхнее перекрытие за сезон в зависимости от R (кривая) ──
def f_heatloss():
    ox, oy, W, H = 60, 20, 640, 240
    gsop = 4360
    rmin, rmax = 0.3, 7.0
    sx = W / (rmax - rmin)
    pmax = 24 * gsop / rmin / 1000
    sy = H / min(pmax, 300)
    b = ""
    for r in (1, 2, 3, 4, 5, 6, 7):
        x = ox + (r - rmin) * sx
        b += L(x, oy, x, oy + H, "#e4e5e8", 1) + T(x, oy + H + 18, str(r), 12, MUT, "middle")
    for p in (0, 50, 100, 150, 200, 250, 300):
        y = oy + H - p * sy
        b += L(ox, y, ox + W, y, "#e4e5e8", 1) + T(ox - 8, y + 4, str(p), 12, MUT, "end")
    pts = []
    r = rmin
    while r <= rmax + 1e-9:
        p = min(24 * gsop / r / 1000, 300)
        pts.append((ox + (r - rmin) * sx, oy + H - p * sy))
        r += 0.03
    b += PL(pts, RED, 3)
    xr = ox + (3.0 - rmin) * sx
    b += L(xr, oy, xr, oy + H, MUT, 1.5, "6 4") + T(xr + 6, oy + 14, "норматив чердачное (R = 3,0)", 11, MUT)
    for r_m in (0.4, 3.0, 5.2, 6.5):
        p = round(24 * gsop / r_m / 1000)
        x = ox + (r_m - rmin) * sx
        y = oy + H - min(p, 300) * sy
        b += f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4" fill="{RED}"/>'
        b += T(x + 8, y - 8, f"R={str(r_m).replace('.', ',')}", 11, INK, "start", "700") + T(x + 8, y + 8, f"{p} кВт·ч", 11, INK, "start", "700")
    b += T(ox + W / 2, oy + H + 40, "сопротивление теплопередаче R, м²·°С/Вт", 12, MUT, "middle")
    b += T(14, oy - 4, "теплопотери за сезон, кВт·ч/м²", 11, MUT)
    return fig(720, oy + H + 60, b, "Теплопотери верхнего перекрытия за отопительный сезон", "Рис. 8. Теплопотери 1 м² верхнего перекрытия за отопительный сезон (Минск, ГСОП ≈ 4360 °С·сут) в зависимости от R: 24×ГСОП/R. Без утепления (R≈0,4) и с ватой 250 мм (R≈6,5) — разница в 16 раз.")
