SEPTS = [1, 1.5, 2, 2.5, 3, 4, 5, 6, 8, 10]
LOW = {"песок": 30, "супесь": 20, "суглинок": 10}


def _std(v):
    for s in SEPTS:
        if s >= v:
            return s
    return None


def _calc_rows():
    rows = []
    for n in (2, 4, 6):
        for lpd in (150, 200):
            q = n * lpd / 1000.0
            v = 3 * q
            vr = v * 1.2
            rows.append([f"{n}", f"{lpd}", ru(q, 2), ru(v, 1), ru(vr, 1), ru(_std(vr), 1) if _std(vr) else "—",
                         "две" if q <= 1 else "три",
                         ru(q * 14, 1)])
    return rows


def _field_rows():
    rows = []
    for n in (2, 4, 6):
        q = n * 200 / 1000.0 * 1000
        cells = []
        for nm in ("песок", "супесь", "суглинок"):
            cells.append(f"{ru(q / SOIL_LOAD[nm], 0)} / {ru(q / LOW[nm], 0)}")
        rows.append([f"{n} чел., {ru(q, 0)} л/сут"] + cells)
    return rows


