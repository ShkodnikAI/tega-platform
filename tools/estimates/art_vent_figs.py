    rows = [("Старый дом, n50 = 6", 6), ("Обычный, окна ПВХ, n50 = 3", 3), ("Новый энергоэффективный, n50 = 1,5", 1.5), ("Пассивный дом, n50 = 0,6", 0.6)]
