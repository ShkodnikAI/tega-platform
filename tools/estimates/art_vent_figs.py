# ── Физика ──
def stack_pa(h, t_out, t_in=20.0):
    """Естественная тяга шахты, Па: Δp = 3460 · h · (1/Tн − 1/Tв)."""
    return 3460.0 * h * (1.0 / (273.15 + t_out) - 1.0 / (273.15 + t_in))


def depress_pa(q_imbalance, volume, n50):
    """Разрежение, Па, при дисбалансе расходов q (м³/ч): q = (n50·V)·(Δp/50)^0,65."""
    return 50.0 * (q_imbalance / (n50 * volume)) ** (1 / 0.65)


def dew_point(t, rh):
    import math
    a, b = 17.62, 243.12
    g = math.log(rh / 100.0) + a * t / (b + t)
    return b * g / (a - g)


