# ── 3. Естественная тяга от температуры ──
def f_draft():
    ox, oy, W, H = 64, 18, 600, 300
    t0, t1, ymin, ymax = -25, 30, -10, 35
    sx, sy = W / (t1 - t0), H / (ymax - ymin)

    def X(t):
        return ox + (t - t0) * sx

    def Y(p):
        return oy + (ymax - p) * sy
    b = R(ox, Y(0), W, (0 - ymin) * sy, SOFT)
    for t in range(-20, 31, 10):
        b += L(X(t), oy, X(t), oy + H, "#e4e5e8", 1) + T(X(t), oy + H + 18, f"{t}".replace("-", "−"), 12, MUT, "middle")
    for p in range(-10, 36, 5):
        b += L(ox, Y(p), ox + W, Y(p), "#e4e5e8", 1) + T(ox - 8, Y(p) + 4, f"{p}".replace("-", "−"), 12, MUT, "end")
    b += L(ox, Y(0), ox + W, Y(0), MUT, 1.5)
    b += T(ox + 8, Y(0) + 18, "обратная тяга: воздух идёт в комнату", 12, RED, "start", "700")
    b += L(ox, Y(4), ox + W, Y(4), RED, 1.5, "5 4") + TH(ox + W - 8, Y(4) - 6, "4 Па: предел разрежения для открытой топки", 12, RED, "end")
    for h, col, nm, sw in ((3, G1, "частный дом, шахта 3 м", 2.5), (9, INK, "3 этажа, шахта 9 м", 3), (18, RED, "6 этажей, шахта 18 м", 3)):
        pts = [(round(X(t), 1), round(Y(stack_pa(h, t)), 1)) for t in range(t0, t1 + 1, 5)]
        b += PL(pts, col, sw)
    b += T(ox + W / 2, oy + H + 40, "температура наружного воздуха, °С (в помещении +20 °С)", 12, MUT, "middle") + T(14, oy + 4, "Па", 12, MUT)
    ly = oy + 8
    for i, (col, nm) in enumerate(((G1, "частный дом, шахта 3 м"), (INK, "3 этажа, шахта 9 м"), (RED, "6 этажей, шахта 18 м"))):
        b += L(ox + W - 200, ly + 6 + i * 20, ox + W - 170, ly + 6 + i * 20, col, 3) + T(ox + W - 162, ly + 10 + i * 20, nm, 12)
    return fig(700, 386, b, "Естественная тяга вентиляционной шахты в зависимости от температуры на улице",
               "Давление естественной тяги по формуле Δp = 3460 · h · (1/Tн − 1/Tв). Зимой тяга максимальна, в межсезонье мала, в жару нулевая или обратная: именно тогда шахты опрокидываются первыми. "
               "Ветер добавляет к этому давлению несколько паскалей в любую сторону.")


