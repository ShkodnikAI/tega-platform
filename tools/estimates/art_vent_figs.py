               f"Разрежение при вытяжке {Q} м³/ч без притока в объёме {V} м³ (≈ 100 м² при потолке 2,5 м): Δp = 50 · (Q ÷ (n50 · V))^(1/0,65). Чем герметичнее дом, тем сильнее разрежение. "
