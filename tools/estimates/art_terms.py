def _grid(rows):
    """Пооперационный график по дням: С — стяжка, · — выдержка, П — плитка."""
    head = ["Помещение"] + [str(i) for i in range(1, 13)]
    return _tbl(head, [[n] + list(c) for n, c in rows])


