def poly(pts, fill="none", stroke=INK, sw=2):
    p = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
    return f'<polygon points="{p}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" stroke-linejoin="round"/>'


def _wrap(s, n):
    words, line, out = s.split(), "", []
    for w in words:
        if len(line + " " + w) > n and line:
            out.append(line)
            line = w
        else:
            line = (line + " " + w).strip()
    out.append(line)
    return out


def _foot(x, y, text, n=118, size=10.5, fill=MUT, lh=14):
    return "".join(T(x, y + k * lh, ln, size, fill) for k, ln in enumerate(_wrap(text, n)))


