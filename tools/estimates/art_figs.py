import math

INK, RED, MUT, G1, G2, G3, SOFT = "#1d1f23", "#e3000f", "#4a4d55", "#7d8089", "#9a9ca3", "#c6c8cd", "#f6f6f7"


def T(x, y, s, size=13, fill=INK, anchor="start", weight="400"):
    return f'<text x="{x}" y="{y}" font-size="{size}" fill="{fill}" text-anchor="{anchor}" font-weight="{weight}">{s}</text>'


def R(x, y, w, h, fill="none", stroke="none", sw=1.5, rx=0):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>'


def L(x1, y1, x2, y2, stroke=INK, w=2, dash=""):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{stroke}" stroke-width="{w}"{d}/>'


def PL(pts, stroke=INK, w=2.5, dash=""):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    p = " ".join(f"{x},{y}" for x, y in pts)
    return f'<polyline points="{p}" fill="none" stroke="{stroke}" stroke-width="{w}"{d} stroke-linejoin="round"/>'


def arrow(x1, y1, x2, y2, stroke=INK, w=2):
    ang = math.atan2(y2 - y1, x2 - x1)
    a = 9
    p1 = (x2 - a * math.cos(ang - 0.45), y2 - a * math.sin(ang - 0.45))
    p2 = (x2 - a * math.cos(ang + 0.45), y2 - a * math.sin(ang + 0.45))
    return (L(x1, y1, x2, y2, stroke, w)
            + f'<polygon points="{x2},{y2} {p1[0]:.1f},{p1[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}" fill="{stroke}"/>')


def fig(w, h, body, label, caption):
    return (f'<figure class="e-fig"><svg viewBox="0 0 {w} {h}" role="img" aria-label="{label}" xmlns="http://www.w3.org/2000/svg">{body}</svg>'
            f'<figcaption>{caption}</figcaption></figure>')


