def f(label, id_, value, unit="", wide=False, mode="decimal"):
    u = f'<span class="u">{unit}</span>' if unit else ""
    w = " wide" if wide else ""
    return (
        f'<div class="e-f{w}"><label for="{id_}">{label}</label>'
        f'<div class="e-in"><input id="{id_}" inputmode="{mode}" autocomplete="off" value="{value}">{u}</div></div>'
    )


def sel(label, id_, options, wide=False):
    o = "".join(f'<option value="{v}"{" selected" if i == 0 else ""}>{t}</option>' for i, (v, t) in enumerate(options))
    w = " wide" if wide else ""
    return f'<div class="e-f{w}"><label for="{id_}">{label}</label><div class="e-in"><select id="{id_}">{o}</select></div></div>'


def seg(name, options, legend):
    o = "".join(
        f'<label><input type="radio" name="{name}" value="{v}"{" checked" if i == 0 else ""}><span>{t}</span></label>'
        for i, (v, t) in enumerate(options)
    )
    return f'<fieldset class="e-seg"><legend>{legend}</legend>{o}</fieldset>'


def seg_checked(name, options, legend, checked):
    o = "".join(
        f'<label><input type="radio" name="{name}" value="{v}"{" checked" if v == checked else ""}><span>{t}</span></label>'
        for v, t in options
    )
    return f'<fieldset class="e-seg"><legend>{legend}</legend>{o}</fieldset>'


def kv(k, id_, v="—"):
    return f'<div class="kv"><span>{k}</span><b id="{id_}">{v}</b></div>'


def out(title, rows, verdict_id, extra=""):
    return (
        f'<div class="e-out"><span class="ot">{title}</span>{rows}'
        f'<div class="verdict" id="{verdict_id}" role="status"></div>{extra}</div>'
    )


def panel(id_, num, title, sub, form, output, formula=""):
    fm = f'<div class="e-formula">{formula}</div>' if formula else ""
