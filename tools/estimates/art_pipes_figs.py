def flow_lph(q_kw, dt):
    """Расход теплоносителя, л/ч: G = 860 · Q / ΔT (Q в кВт)."""
    return 860.0 * q_kw / dt


def velocity(g_lph, d_mm):
    a = math.pi * (d_mm / 1000.0) ** 2 / 4
    return g_lph / 1000.0 / 3600.0 / a


def power_kw(d_mm, dt, v=0.5):
    a = math.pi * (d_mm / 1000.0) ** 2 / 4
    return v * a * 980.0 * 4.19 * dt


