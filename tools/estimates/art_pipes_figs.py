def f_weld():
    b = ""
    cases = [(120, "Норма", INK, ["гладкий поясок снаружи,", "проход почти не тронут:", "потеря сечения 10–25 %"]),
             (380, "Перегрев", RED, ["грат внутрь трубы:", "сечение −30…−60 %, место", "накопления шлама и засора"]),
             (640, "Недогрев, проворот", MUT, ["несплавление и трещины:", "течь по стыку", "через 1–3 сезона"])]
    for cx, title, col, lines in cases:
        b += T(cx, 24, title, 16, col, "middle", "700")
        b += f'<circle cx="{cx}" cy="100" r="58" fill="{SOFT}" stroke="{INK}" stroke-width="2.5"/>'
        if title == "Норма":
            b += f'<circle cx="{cx}" cy="100" r="42" fill="#fff" stroke="{G2}" stroke-width="7"/>'
        elif title == "Перегрев":
            b += f'<circle cx="{cx}" cy="100" r="40" fill="#ee4a56" stroke="none"/><circle cx="{cx}" cy="100" r="22" fill="#fff" stroke="{RED}" stroke-width="2.5"/>'
        else:
            b += f'<circle cx="{cx}" cy="100" r="38" fill="#fff" stroke="{MUT}" stroke-width="2.5"/>'
            for ang in (-40, 70, 200):
                a = math.radians(ang)
                b += L(cx + 38 * math.cos(a), 100 + 38 * math.sin(a), cx + 56 * math.cos(a), 100 + 56 * math.sin(a), MUT, 3)
        for k, ln in enumerate(lines):
            b += T(cx, 190 + k * 18, ln, 12, col if title != "Норма" else INK, "middle")
    return fig(760, 260, b, "Три исхода сварки PP-R: норма, перегрев, недогрев",
               "Три исхода сварки PP-R: норма, перегрев (грат внутрь: скрытое заужение и будущий засор), недогрев или проворот (течь через 1–3 сезона). Перегрев не виден снаружи, в этом и опасность.")


