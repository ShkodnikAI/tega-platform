# ── Рис.6: теплопотери за сезон в зависимости от R0 (кривая) ──
def f_teplopoteri():
    ox, oy, W, H = 60, 20, 640, 240
    gsop = 4360
    rmin, rmax = 1.0, 6.5
    sx = W / (rmax - rmin)
    pmax = 24 * gsop / rmin / 1000
    sy = H / pmax
    b = ""
    for r in (1, 2, 3, 4, 5, 6):
        x = ox + (r - rmin) * sx
        b += L(x, oy, x, oy + H, "#e4e5e8", 1) + T(x, oy + H + 18, str(r), 12, MUT, "middle")
    for p in (0, 20, 40, 60, 80, 100):
        y = oy + H - p * sy
        b += L(ox, y, ox + W, y, "#e4e5e8", 1) + T(ox - 8, y + 4, str(p), 12, MUT, "end")
    pts = []
    r = rmin
    while r <= rmax + 1e-9:
        p = 24 * gsop / r / 1000
        pts.append((ox + (r - rmin) * sx, oy + H - p * sy))
        r += 0.05
    b += PL(pts, RED, 3)
    xr = ox + (2.8 - rmin) * sx
    b += L(xr, oy, xr, oy + H, MUT, 1.5, "6 4") + T(xr + 6, oy + 14, "норматив РБ (R0 = 2,8)", 11, MUT)
    for r_m in (1.8, 2.8, 3.6, 5.2):
        p = round(24 * gsop / r_m / 1000)
        x = ox + (r_m - rmin) * sx
        y = oy + H - p * sy
        b += f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4" fill="{RED}"/>'
        b += T(x + 8, y - 8, f"R={str(r_m).replace('.', ',')}", 11, INK, "start", "700") + T(x + 8, y + 8, f"{p} кВт·ч", 11, INK, "start", "700")
    b += T(ox + W / 2, oy + H + 40, "сопротивление теплопередаче стены R0, м²·°С/Вт", 12, MUT, "middle")
    b += T(14, oy - 4, "теплопотери за сезон, кВт·ч/м²", 11, MUT)
    return fig(720, oy + H + 60, b, "Теплопотери стены за отопительный сезон", "Рис. 6. Теплопотери 1 м² стены за отопительный сезон (Минск, ГСОП ≈ 4360 °С·сут) в зависимости от R0: 24×ГСОП/R0.")


