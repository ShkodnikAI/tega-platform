import math
from art_figs import T, R, L, PL, arrow, fig, INK, RED, MUT, G1, G2, G3, SOFT


def _donut(data, center_big, center_small, legend_x=280):
    cx, cy, ro, ri = 130, 130, 110, 66
    b, a0 = "", -math.pi / 2
    for name, v, c in data:
        a1 = a0 + 2 * math.pi * v / 100
        x0, y0, x1, y1 = cx + ro * math.cos(a0), cy + ro * math.sin(a0), cx + ro * math.cos(a1), cy + ro * math.sin(a1)
        x2, y2, x3, y3 = cx + ri * math.cos(a1), cy + ri * math.sin(a1), cx + ri * math.cos(a0), cy + ri * math.sin(a0)
        large = 1 if v > 50 else 0
        b += (f'<path d="M{x0:.1f},{y0:.1f} A{ro},{ro} 0 {large} 1 {x1:.1f},{y1:.1f} L{x2:.1f},{y2:.1f} A{ri},{ri} 0 {large} 0 {x3:.1f},{y3:.1f} Z" '
              f'fill="{c}" stroke="#ffffff" stroke-width="2"/>')
        a0 = a1
    b += T(cx, cy - 6, center_big, 22, INK, "middle", "700") + T(cx, cy + 16, center_small, 12, MUT, "middle")
    for i, (name, v, c) in enumerate(data):
        y = 40 + i * 32
        b += R(legend_x, y - 13, 16, 16, c) + T(legend_x + 26, y, name, 14) + T(legend_x + 360, y, f"{v} %", 14, INK, "end", "700")
    return b


