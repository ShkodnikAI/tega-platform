# ── Рис.3: мощность ТН в зависимости от температуры воздуха (точка бивалентности) ──
def f_bivalent():
    ox, oy, W, H = 60, 20, 640, 220
    # Pнад(A7)=11 кВт, k: 7°C→1.0, -7→0.75, -15→0.60, -25→0.50 (кусочно-линейно); Qd=8.6 кВт на -24°C
    pts_k = [(7, 1.0), (-7, 0.75), (-15, 0.60), (-25, 0.50)]
    pnom = 11.0
    tmin, tmax = -28, 10
    sx = W / (tmax - tmin)
    pmax = 12
    sy = H / pmax
    b = ""
    for p in (0, 2, 4, 6, 8, 10, 12):
        y = oy + H - p * sy
        b += L(ox, y, ox + W, y, "#e4e5e8", 1) + T(ox - 8, y + 4, str(p), 11, MUT, "end")
    for t in (-25, -20, -15, -10, -7, 0, 7):
        x = ox + (t - tmin) * sx
        b += L(x, oy, x, oy + H, "#e4e5e8", 1) + T(x, oy + H + 18, str(t), 11, MUT, "middle")
    pts = []
    t = tmax
    while t >= tmin - 1e-9:
        if t >= pts_k[0][0]:
            k = pts_k[0][1]
        elif t <= pts_k[-1][0]:
            k = pts_k[-1][1]
        else:
            for (t1, k1), (t2, k2) in zip(pts_k, pts_k[1:]):
                if t2 <= t <= t1:
                    k = k2 + (k1 - k2) * (t - t2) / (t1 - t2)
                    break
        pts.append((ox + (t - tmin) * sx, oy + H - pnom * k * sy))
        t -= 0.5
    b += PL(pts, RED, 3)
    qd_y = oy + H - 8.6 * sy
    b += L(ox, qd_y, ox + W, qd_y, INK, 1.5, "6 4") + T(ox + 6, qd_y - 8, "теплопотери дома Qd = 8,6 кВт (Минск, −24 °C)", 11, INK, "start", "700")
    xb = ox + (-10 - tmin) * sx
    b += L(xb, oy, xb, oy + H, MUT, 1.5, "3 4") + T(xb + 6, oy + 16, "точка бивалентности", 11, MUT, "start")
    b += T(ox + W / 2, oy + H + 40, "температура наружного воздуха, °C", 12, MUT, "middle")
    b += T(14, oy - 4, "мощность ТН, кВт", 11, MUT)
    return fig(720, oy + H + 60, b, "Падение мощности воздушного ТН с морозом", "Рис. 3. Падение располагаемой мощности воздушного ТН (паспорт 11 кВт при A7/W35) с понижением температуры. Ниже точки бивалентности мощности не хватает на расчётные теплопотери Qd — догрев берёт ТЭН, каскад или резервный котёл.")


