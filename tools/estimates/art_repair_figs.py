from art_figs import T, R, L, arrow, fig, INK, RED, MUT, G1, G2, G3, SOFT


def f_chain():
    steps = [("Осмотр", "износ и дефекты с объёмами"), ("Дефектный акт", "форма С-1, даты и срок"), ("Лок. смета", "только она, без ССР"),
             ("Закупка", "процедура по сумме"), ("Договор", "неизменная цена, график"), ("Работы", "допработы только по акту"), ("Приёмка", "акт С-2а, справка")]
    b = ""
    for i, (a, c) in enumerate(steps):
        x = 4 + i * 108
        col = RED if i == 1 else INK
        b += R(x, 8, 100, 98, col) + T(x + 10, 34, str(i + 1), 18, "#ffd0d4" if i == 1 else "#9a9ca3", "start", "700")
        b += T(x + 8, 58, a, 11, "#fff", "start", "700")
        words = c.split(" ")
        line, y = "", 76
        for w in words:
            if len(line + " " + w) > 15 and line:
                b += T(x + 10, y, line, 10.5, "#dcdde0")
                line, y = w, y + 14
            else:
                line = (line + " " + w).strip()
        b += T(x + 10, y, line, 10.5, "#dcdde0")
    return fig(760, 114, b, "Цепочка документов текущего ремонта",
               "Семь шагов. Красным отмечен дефектный акт: в нём заказчик фиксирует объёмы, дату начала и срок, от них зависят смета и цена. Задним числом он не исправляется.")


def f_ladder():
    rows = [("Техническое обслуживание", "поддержание: мелкие неисправности, регламент, сезонная подготовка", G3, INK),
            ("Текущий ремонт", "предупреждение износа, устранение повреждений, улучшение эстетики. Дефектный акт и смета", RED, "#fff"),
            ("Капитальный ремонт", "восстановление, усиление и замена конструкций и систем. Проект и разрешения", INK, "#fff"),
            ("Модернизация, реконструкция", "новые системы, перепланировка, изменение назначения и параметров", MUT, "#fff")]
    b = ""
