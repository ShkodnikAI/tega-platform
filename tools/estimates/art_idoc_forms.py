def _match(rules, text):
    t = text.strip().lower()
    for pref, k in rules:
        if t.startswith(pref):
            return k
    return None


def tag_roles(forms):
    """Размечает строки комиссии и подписи ролями и записывает form['parties'] в порядке появления."""
    for f in forms:
        order = []
        for b in f["blocks"]:
            if b.get("role") and b["role"] not in order:
                order.append(b["role"])
            if b.get("k") == "p" and "[[" in b["text"] and not b.get("role"):
                pre = b["text"].split("[[", 1)[0]
                if len(pre) < 140 and "произвела" not in pre and not pre.lstrip()[:1].isdigit():
                    k = _match(_LINE_RULES, pre)
                    if k:
                        b["role"] = k
                        if k not in order:
                            order.append(k)
            elif b.get("k") == "sign":
                b["keys"] = [_match(_SIGN_RULES, r) for r in b["roles"]]
                for k in b["keys"]:
                    if k and k not in order:
                        order.append(k)
        f["parties"] = [{"k": k, "label": PARTY[k][0], "def": PARTY[k][1]} for k in order] if len(order) > 1 else []


