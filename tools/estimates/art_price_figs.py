"""Рисунки статьи «Из чего состоит цена строительных работ»: чистый SVG без встроенных стилей и скриптов (CSP сайта их не пропускает).
Числа взяты из образца ТЕГА ПЛЮС (структура статей ОХР и ОПР) и проверены по суммам: группы 56,37 + 24,81 + 15,13 + 3,69 = 100,00."""
from art_figs import T, R, L, PL, arrow, fig, INK, RED, MUT, G1, G2, G3, SOFT
from art_vent_figs import ru

NORM = 67.30
GROUPS = [("А", "Административно-хозяйственные", 56.37, INK), ("Б", "Обслуживание работников", 24.81, RED), ("В", "Организация работ на площадках", 15.13, G1), ("Г", "Прочие накладные", 3.69, G3)]


def f_groups():
    ox, oy, W = 20, 36, 720
    b = T(ox, 22, "Структура норм ОХР и ОПР 67,30 % по четырём группам (доли в норме)", 13, INK, "start", "700")
    x = ox
    for k, nm, v, col in GROUPS:
        w = W * v / 100.0
        b += R(x, oy, w, 54, col)
        if w > 60:
            b += T(x + w / 2, oy + 33, f"{k} · {ru(v, 2)} %", 14, "#fff" if col != G3 else INK, "middle", "700")
        x += w
    b += T(x - 6, oy + 70, f"Г · {ru(3.69, 2)} %", 12, MUT, "end")
    y = oy + 96
    for k, nm, v, col in GROUPS:
        b += R(ox, y - 11, 12, 12, col) + T(ox + 20, y, f"{k}. {nm}: {ru(v, 2)} % группы, это {ru(NORM * v / 100, 2)} п. п. из {ru(NORM, 2)}", 13, INK)
        y += 24
    return fig(760, 214, b, "Структура норм общехозяйственных и общепроизводственных расходов",
               "Четыре группы затрат внутри нормы ОХР и ОПР. В пересчёте на норму 67,30 % к базе (зарплата рабочих и машинистов): А 37,94 п. п., Б 16,70, В 10,18, Г 2,48. Структура по таблице образца, сверяйте с первоисточником.")


def f_k():
    ox, oy, W = 40, 60, 680
    lo, hi = 0.5, 1.0
    X = lambda k: ox + (k - lo) / (hi - lo) * W
    b = R(ox, oy, W, 24, SOFT, G3, 1) + R(X(0.9), oy, X(1.0) - X(0.9), 24, "#dcdde0")
    b += R(ox, oy, X(0.9) - ox, 24, "#fbd5d8")
    for k in (0.5, 0.6, 0.7, 0.8, 0.9, 1.0):
        b += L(X(k), oy + 24, X(k), oy + 32, MUT, 1) + T(X(k), oy + 48, ru(k, 2), 11, MUT, "middle")
    b += L(X(0.9), oy - 14, X(0.9), oy + 24, RED, 3) + T(X(0.9), oy - 20, "0,90: нижняя граница по образцу", 12, RED, "middle", "700")
    pts = [(0.85, "−15 %"), (0.75, "−25 %"), (0.57, "−43 %")]
    for k, lab in pts:
        b += f'<circle cx="{X(k):.1f}" cy="{oy + 12}" r="6" fill="{INK}"/>' + T(X(k), oy + 78, f"k = {ru(k, 2)}: {lab}", 12, INK, "middle", "700")
    b += T(X(0.95), oy + 78, "k = 0,90 … 1,00", 12, MUT, "middle")
    b += T(ox, 26, "Конкурсный коэффициент k и снижение цены относительно цены заказчика", 13, INK, "start", "700")
    return fig(760, 172, b, "Шкала конкурсного коэффициента",
               "Снижение цены равно 1 − k. Левее красной черты (k ниже 0,9) цена выходит за границу, о которой говорит образец: снижение больше 10 % от цены заказчика.")
