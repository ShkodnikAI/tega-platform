def f_steps():
    steps = [("1", "Режим", "температура", "и влажность"), ("2", "Объём", "размеры", "парной"), ("3", "Ограждения", "пирог и", "вентиляция"),
             ("4", "Печь", "мощность", "по объёму"), ("5", "Электрика", "сечение, защита,", "пожар"), ("6", "Отделка и пуск", "тесты до", "облицовки")]
    b = ""
    for i, (n, t, s1, s2) in enumerate(steps):
        x = 6 + i * 125
        col = RED if i == 0 else INK
        b += R(x, 14, 115, 96, col) + T(x + 12, 42, n, 22, "#fff", "start", "700") + T(x + 12, 66, t, 13, "#fff", "start", "700")
        b += T(x + 12, 84, s1, 10.5, "#dcdde0") + T(x + 12, 98, s2, 10.5, "#dcdde0")
        if i < 5:
            b += arrow(x + 116, 62, x + 124, 62, MUT, 2)
    b += T(6, 136, "Начинают с режима, а не с печи из каталога. Перестановка шагов даёт типичные переделки: недогрев, сырость, выбитый автомат.", 12, MUT)
    return fig(760, 150, b, "Шесть шагов проектирования бани", "Порядок решений: сначала режим, потом ограждения и печь, электрика и пожарные узлы, и только в конце отделка.")


def f_modes():
    ox, oy, w, h = 70, 20, 640, 270
    def X(rh): return ox + rh / 100 * w
    def Y(t): return oy + h - (t - 20) / 90 * h
    b = R(ox, oy, w, h, SOFT, G3, 1)
    for t in (30, 50, 70, 90, 110):
        b += L(ox, Y(t), ox + w, Y(t), G3, 1, "3 4") + T(ox - 8, Y(t) + 4, f"{t}", 11, MUT, "end")
    for rh in (0, 20, 40, 60, 80, 100):
        b += L(X(rh), oy, X(rh), oy + h, G3, 1, "3 4") + T(X(rh), oy + h + 16, f"{rh}", 11, MUT, "middle")
    b += T(ox - 36, oy + 4, "°C", 11, MUT, "end") + T(ox + w, oy + h + 32, "относительная влажность, %", 11, MUT, "end")
    zones = [("Финская сауна", 10, 20, 80, 100, INK, "80–100 °C, 10–20 %"), ("Русская баня", 40, 60, 60, 70, G1, "60–70 °C, 40–60 %"),
             ("Хамам", 90, 100, 40, 50, RED, "40–50 °C, 90–100 %"), ("ИК-кабина", 10, 30, 45, 60, G2, "45–60 °C, воздух сухой")]
    for nm, r0, r1, t0, t1, col, sub in zones:
        b += R(X(r0), Y(t1), X(r1) - X(r0), Y(t0) - Y(t1), col)
    b += TH(X(10) + 6, Y(100) - 8, "Финская сауна: 80–100 °C, 10–20 %", 12, INK, "start", "700")
    b += TH(X(40) + 4, Y(70) - 8, "Русская баня: 60–70 °C, 40–60 %", 12, INK, "start", "700")
    b += TH(X(100), Y(50) - 8, "Хамам: 40–50 °C, 90–100 %", 12, RED, "end", "700")
    b += TH(X(10), Y(45) + 18, "ИК-кабина: 45–60 °C, воздух сухой", 12, INK, "start", "700")
    return fig(760, 330, b, "Карта температура-влажность для четырёх режимов", "Режим это точка и область на карте. От неё зависят тип печи, ограждения, вентиляция и электрика. Диапазоны ориентиры практики, не нормативы.")


def f_layers():
    x0, y0, hh = 40, 24, 120
    parts = [("Стена", 120, G3), ("Вата 50 мм", 100, "#e8d9a8"), ("Фольга", 8, G1), ("Зазор 20 мм", 40, "#ffffff"), ("Вагонка", 50, "#c9a56b")]
    b = ""
    x = x0
    centers = []
    for nm, wd, fill in parts:
        b += R(x, y0, wd, hh, fill, INK, 1.5)
        centers.append(x + wd / 2)
        x += wd
    b += arrow(x + 46, y0 + 62, x + 8, y0 + 62, RED, 2) + T(x + 8, y0 + 50, "парная", 13, RED, "start", "700")
    labels = [("Стена", 0), ("Базальтовая вата", 1), ("Алюминиевая фольга", 2), ("Вентзазор", 0), ("Вагонка", 1)]
    for i, (a_, row) in enumerate(labels):
        cx = centers[i]
        by = y0 + hh + 26 + row * 24
        b += L(cx, y0 + hh, cx, by - 14, G1, 1, "2 3")
        b += T(cx, by, a_, 12, INK, "middle", "700")
    tx = x0 + 400
    b += T(tx, y0 + 20, "Разрез стены сауны", 13, INK, "start", "700")
    b += T(tx, y0 + 44, "слои слева направо: стена, парная справа", 12, MUT)
    b += T(tx, y0 + 72, "Фольга одна и непрерывная: это и", 12, MUT) + T(tx, y0 + 90, "пароизоляция, и отражатель тепла.", 12, MUT) + T(tx, y0 + 108, "Без неё вата отсыревает.", 12, MUT)
    b += T(tx, y0 + 136, "Потолок: вата 100 мм, тот же порядок слоёв.", 12, MUT)
    return fig(760, 224, b, "Пирог стены сауны", "Порядок слоёв и зазор важнее толщины ваты. Пенопласт в парной не применяют: только базальтовая вата.")


