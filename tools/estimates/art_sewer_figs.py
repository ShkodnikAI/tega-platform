def f_bod():
    rows = [("Накопитель", None, None, "очистки нет, только хранение", G3),
            ("Септик без доочистки", 30, 60, "30–60 %", G1),
            ("Септик + почвенная доочистка", 85, 95, "85–95 %", MUT),
            ("Станция биоочистки", 90, 98, "90–98 %", INK),
            ("СБО + биофильтр или мембрана", 95, 99, "95–99 %", RED)]
    ox, oy, w, rh = 250, 20, 440, 44
    sc = w / 100.0
    b = ""
    for v in (0, 20, 40, 60, 80, 100):
        b += L(ox + v * sc, oy - 6, ox + v * sc, oy + rh * len(rows), "#e4e5e8", 1) + T(ox + v * sc, oy + rh * len(rows) + 18, str(v), 12, MUT, "middle")
    for i, (nm, lo, hi, lab, col) in enumerate(rows):
        y = oy + i * rh
        b += T(ox - 12, y + 26, nm, 13, INK, "end")
        if lo is None:
            b += R(ox, y + 10, 5, 22, col) + T(ox + 14, y + 26, lab, 12, MUT)
        else:
            b += R(ox + lo * sc, y + 10, (hi - lo) * sc, 22, col) + TH(ox + hi * sc + 8, y + 26, lab, 12, INK, "start", "700")
    b += T(ox + w / 2, oy + rh * len(rows) + 42, "снижение БПК (органической нагрузки), %", 12, MUT, "middle")
    return fig(780, 300, b, "Ориентировочное снижение органической нагрузки (БПК) по схемам",
               "Ориентиры по литературе и паспортам (для станции берут значение из паспорта): диапазоны зависят от нагрузки, температуры и обслуживания. Разрыв между «септик сам по себе» и схемами "
               "с аэробной стадией принципиальный. Фактическое качество очистки берут из паспорта изделия и протоколов испытаний.")


