def f_volume():
    groups = [(2, "2 чел."), (4, "4 чел."), (6, "6 чел.")]
    ox, oy, hh = 70, 30, 220
    sc = hh / 4.0
    b = L(ox, oy, ox, oy + hh, MUT, 1) + L(ox, oy + hh, ox + 640, oy + hh, MUT, 1) + T(14, oy - 8, "объём септика, м³", 11, MUT)
    for v in (0, 1, 2, 3, 4):
        yy = oy + hh - v * sc
        b += L(ox - 4, yy, ox + 640, yy, "#e4e5e8", 1) + T(ox - 8, yy + 4, str(v), 11, MUT, "end")
    for i, (n, lab) in enumerate(groups):
        gx = ox + 40 + i * 200
        for j, (lpd, col) in enumerate(((150, G1), (200, RED))):
            v = 3 * n * lpd / 1000.0
            x = gx + j * 66
            b += R(x, oy + hh - v * sc, 56, v * sc, col) + T(x + 28, oy + hh - v * sc - 8, ru(v, 1), 14, INK, "middle", "700")
        b += T(gx + 61, oy + hh + 20, lab, 13, INK, "middle")
    b += R(ox + 190, oy - 18, 12, 12, G1) + T(ox + 208, oy - 8, "150 л/чел·сут", 12, MUT)
    b += R(ox + 190, oy + 2, 12, 12, RED) + T(ox + 208, oy + 12, "200 л/чел·сут", 12, MUT)
    return fig(760, 300, b, "Расчётный объём септика на 3 суток притока для 2, 4 и 6 жильцов",
               "Объём септика V = 3 · Q: трое суток притока при 150 и 200 л на человека в сутки. Запас на гостей добавляется отдельно. "
               "Объём возьмите ближайший большой из типоряда ёмкостей.")


