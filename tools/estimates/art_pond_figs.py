def f_turn():
    ox, oy = 150, 40
    b = T(ox, 22, "Оборот воды, объёмов в час", 13, INK, "start", "700")
    sc = 55.0
    rows = [("Декоративный биопруд", 0.5, 1.0, INK), ("Пруд для купания", 1.0, 2.0, G1), ("Кой-пруд", 2.0, 4.0, RED)]
    for i, (nm, a, c, col) in enumerate(rows):
        y = oy + i * 44
        b += T(ox - 10, y + 22, nm, 12, INK, "end") + R(ox + a * sc, y, (c - a) * sc, 30, col) + T(ox + c * sc + 8, y + 21, f"{ru(a, 1)}–{ru(c, 1)}", 13, INK, "start", "700")
