    b += T(6, 148, "Красные звенья опасны для рыбы только до созревания биофильтра (первые 4–6 недель).", 12, MUT)
    return fig(760, 160, b, "Азотный цикл пруда", "Цепочка азота: корм и органика дают аммоний, бактерии переводят его в нитрит и затем в нитрат, нитрат забирают растения. Оборудование ускоряет цикл, но не заменяет его.")


