def T(key, label, cap="", ml=False):
    return "[[%s|%s|%s%s]]" % (key, label, cap, "|ml" if ml else "")


def C(key, label, *opts, kind="~"):
    return "[[%s%s|%s|%s]]" % (kind, key, label, F.SEP.join(opts))


def tbl(key, label, cols, rows=6):
    return {"k": "tbl", "key": key, "label": label, "cols": cols, "min": rows}


