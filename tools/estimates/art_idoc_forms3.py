"""Титульные листы разделов и перечень сертификатов на материалы.

Форма титульного листа и перечня документов о качестве Перечнем исполнительной документации не установлена:
это оформление сайта, а не утверждённая форма. Значения вводятся один раз и подставляются во все акты (static/idoc.js).
Наличие перечня сертификатов в составе акта предусмотрено, например, СП 4.01.07-2024, приложение А.
"""
import art_idoc_forms as F

p, h, title, date, sign = F.p, F.h, F.title, F.date, F.sign
CAP_ORG = F.CAP_ORG


def T(key, label, cap="", ml=False):
    return "[[%s|%s|%s%s]]" % (key, label, cap, "|ml" if ml else "")


def _party(role, text):
    b = p(text)
    b["role"] = role
    return b


NOTE = "Оформление сайта: форма не установлена Перечнем исполнительной документации."

TITLES = [
    ("gen", "tl-gen", "Общестрой"),
    ("vk", "tl-vk", "Водопровод и канализация"),
    ("ot", "tl-ot", "Отопление, вентиляция, кондиционирование"),
    ("ov", "tl-ov", "Отопление, вентиляция, кондиционирование"),
    ("nv", "tl-nv", "Наружные сети водопровода и канализации"),
    ("el", "tl-el", "Электроснабжение и электрооборудование"),
    ("ne", "tl-ne", "Наружные сети электроснабжения"),
]


def build(existing):
    out = []
    for gid, fid, sec in TITLES:
        blocks = [
            title("ИСПОЛНИТЕЛЬНАЯ ДОКУМЕНТАЦИЯ", "Раздел: " + sec),
            p("Объект " + T("obj", "Объект: наименование и место расположения", "наименование и место расположения объекта", True)),
            p("Договор подряда " + T("dog", "Договор подряда: номер и дата", "номер и дата")),
            _party("zak", "Заказчик " + T("zak", "Заказчик: организация, должность, ФИО", CAP_ORG)),
            _party("gp", "Генеральный подрядчик " + T("gp", "Генеральный подрядчик: организация, должность, ФИО", CAP_ORG)),
            _party("smo", "Строительно-монтажная организация " + T("smo", "Строительно-монтажная организация: организация, должность, ФИО", CAP_ORG)),
            _party("sub", "Субподрядная организация " + T("sub", "Субподрядная организация: организация, должность, ФИО", CAP_ORG)),
            _party("proj", "Проектная организация " + T("proj", "Проектная организация: организация, должность, ФИО", CAP_ORG)),
            _party("tn", "Технический надзор заказчика " + T("tn", "Технический надзор заказчика: организация, должность, ФИО", CAP_ORG)),
            _party("an", "Авторский надзор " + T("an", "Авторский надзор: организация, должность, ФИО", CAP_ORG)),
            p("Начало работ " + T("d1", "Дата начала работ", "")),
            p("Окончание работ " + T("d2", "Дата окончания работ", "")),
            date(True),
        ]
        out.append({
            "id": fid, "group": gid, "short": "Титульный лист раздела", "source": "Титульный лист: " + sec,
            "perechen": NOTE.rstrip("."),
            "use": "Данные объекта и фамилии участников, введённые здесь, запоминаются в этом браузере и подставляются во все акты. " + NOTE,
            "blocks": blocks, "title": True,
        })
    out.append({
        "id": "mat-list", "group": "gen", "short": "Перечень сертификатов на материалы (для любого раздела)",
        "source": "Перечень документов о качестве материалов, изделий и конструкций",
        "perechen": NOTE + " Перечень документов о качестве прилагают к актам (например, СП 4.01.07-2024, прил. А)",
        "use": "Список материалов и документов о качестве (сертификат, паспорт: номер, дата, изготовитель) вводят один раз ниже поля выбора акта; он подставляется в акты и печатается здесь. " + NOTE,
        "blocks": [
            title("ПЕРЕЧЕНЬ", "документов о качестве материалов, изделий и конструкций"),
            p("Объект " + T("obj", "Объект: наименование и место расположения", "наименование и место расположения объекта", True)),
            date(True),
            {"k": "mats"},
            _party("smo", "Строительно-монтажная организация " + T("smo", "Строительно-монтажная организация: организация, должность, ФИО", CAP_ORG)),
            _party("tn", "Технический надзор заказчика " + T("tn", "Технический надзор заказчика: организация, должность, ФИО", CAP_ORG)),
            sign(["Представитель строительно-монтажной организации", "Представитель технического надзора заказчика"]),
        ],
    })
    return out
