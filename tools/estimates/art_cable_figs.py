def drop_pct(i, l, s, u=230.0):
    """Потеря напряжения однофазной линии, %: 2·I·ρ·L/S от 230 В."""
    return 2 * i * RHO_CU * l / s / u * 100


def steps_fig(steps, last_red=True):
    b = ""
    n = len(steps)
    for i, (num, t, lines) in enumerate(steps):
        x = 8 + i * 148
        b += R(x, 10, 126, 120, RED if (last_red and i == n - 1) else INK)
        b += T(x + 12, 40, num, 26, "#ffffff", weight="700")
        ty = 62
        for k, ln in enumerate(t):
            b += T(x + 12, ty + k * 16, ln, 13, "#ffffff", weight="700")
        sy = ty + len(t) * 16 + 6
        for k, ln in enumerate(lines):
            b += T(x + 12, sy + k * 13, ln, 10.5, "#dcdde0")
        if i < n - 1:
            b += arrow(x + 128, 70, x + 146, 70, G2, 2)
    return b


