def f_drop():
    ox, oy, W, H = 64, 36, 600, 280
    ymax, lmax = 17.0, 100.0
    sx, sy = W / lmax, H / ymax
    b = ""
    for v in (0, 2.5, 5, 7.5, 10, 12.5, 15):
        yy = oy + H - v * sy
        b += L(ox, yy, ox + W, yy, "#e4e5e8", 1) + T(ox - 8, yy + 4, ru(v, 1), 12, MUT, "end")
    for l in range(0, 101, 20):
        b += T(ox + l * sx, oy + H + 18, str(l), 12, MUT, "middle")
    b += T(ox + W / 2, oy + H + 40, "длина линии L, м (1 фаза, 230 В, I = 16 А, cosφ = 1)", 12, MUT, "middle") + T(14, oy - 14, "потеря напряжения ΔU, %", 12, MUT)
    cols = [(1.5, RED), (2.5, INK), (4, G1), (6, G2)]
    for s, c in cols:
        b += L(ox, oy + H, ox + W, oy + H - drop_pct(16, 100, s) * sy, c, 3)
    b += L(ox, oy + H - 5 * sy, ox + W, oy + H - 5 * sy, RED, 1.8, "6 4") + TH(ox + W - 6, oy + H - 5 * sy - 7, "предел 5 %", 12, RED, "end", "700")
    l25 = 5 / drop_pct(16, 1, 2.5)
    b += T(ox + 150, oy + H - 15.8 * sy, f"2,5 мм² при 16 А: предел уже на ~{round(l25, -1):.0f} м", 12, INK)
    b += L(ox + l25 * sx, oy + H - 15.2 * sy, ox + l25 * sx, oy + H - 5.3 * sy, MUT, 1.2, "3 3")
    for i, (s, c) in enumerate(cols):
        b += L(ox + 12, oy + 12 + i * 20, ox + 40, oy + 12 + i * 20, c, 3) + T(ox + 48, oy + 16 + i * 20, f"S = {ru(s, 1) if s < 4 else int(s)} мм²", 12)
    return fig(740, 366, b, "Потеря напряжения в однофазной линии 16 А в зависимости от длины и сечения",
               "Потеря напряжения в однофазной линии 16 А: уже на 50 м сечение 2,5 мм² выходит за предел 5 %. Для трёх фаз потеря в √3 раз меньше при том же токе фазы.")


