def f_idop():
    ox, oy, W, H = 64, 62, 600, 290
    ymax = 190.0
    sy = H / ymax
    xs = [ox + 30 + i * (W - 60) / (len(SECT) - 1) for i in range(len(SECT))]

    def Y(v):
        return oy + H - v * sy
    b = ""
    for v in range(0, 181, 25):
        b += L(ox, Y(v), ox + W, Y(v), "#e4e5e8", 1) + T(ox - 8, Y(v) + 4, str(v), 12, MUT, "end")
    for v, nm in BREAKERS:
        b += L(ox, Y(v), ox + W, Y(v), G2, 1, "2 3") + T(ox + W + 8, Y(v) + 4, nm, 10, MUT)
    for x, s in zip(xs, SECT):
        b += T(x, oy + H + 18, ru(s, 1) if s < 10 else str(int(s)), 12, MUT, "middle")
    b += T(ox + W / 2, oy + H + 40, "сечение меди, мм²", 12, MUT, "middle") + T(14, 18, "длительно допустимый ток, А", 12, MUT)
    series = [(I_WALL, G1, "tri", "в трубе, гофре, в стене"), (I_AIR, INK, "circ", "открыто в воздухе, на лотке"), (I_GROUND, RED, "sq", "в земле (траншея)")]
    for data, col, mk, nm in series:
        pts = [(round(x, 1), round(Y(v), 1)) for x, v in zip(xs, data)]
        b += PL(pts, col, 3)
        for (x, y) in pts:
            if mk == "circ":
                b += f'<circle cx="{x}" cy="{y}" r="4.5" fill="{col}"/>'
            elif mk == "sq":
                b += R(x - 4.5, y - 4.5, 9, 9, col)
            else:
                b += f'<polygon points="{x},{y - 5.5} {x - 5},{y + 4} {x + 5},{y + 4}" fill="{col}"/>'
    ly = 36
    for i, (data, col, mk, nm) in enumerate(series):
        lx = ox + 6 + i * 200
        b += L(lx, ly + 2, lx + 24, ly + 2, col, 3) + T(lx + 30, ly + 6, nm, 12)
    b += L(xs[1], Y(112), xs[1], Y(I_GROUND[1]) - 8, MUT, 1.2, "3 3") + T(xs[1] - 6, Y(120), "2,5 мм²: воздух 27 А, стена 24 А, земля 37 А", 12, INK)
    return fig(740, 392, b, "Длительно допустимый ток меди с ПВХ-изоляцией в зависимости от сечения и способа прокладки",
               "Длительно допустимые токи меди с ПВХ-изоляцией по способу прокладки (справочные значения по таблицам ПУЭ и каталогам производителей, среда +25 °С). "
               "Серые пунктирные линии справа — номиналы автоматов: видно, какое сечение «держит» каждый номинал.")


