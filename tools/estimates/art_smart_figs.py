"""Инфографика статьи «Умный дом»: чистый SVG без встроенных стилей и скриптов (CSP сайта их не пропускает)."""
from art_figs import T, R, L, PL, arrow, fig, INK, RED, MUT, G1, G2, G3, SOFT


def f_steps():
    steps = [("Сценарии", "что и когда происходит"), ("Зоны и архитектура", "шина или радио"), ("Протокол", "и открытость"),
             ("Электрика", "нейтраль, кабель, ИБП"), ("Монтаж", "и пусконаладка"), ("Сдача", "тесты и документы")]
    b = ""
    for i, (a, c) in enumerate(steps):
        x = 6 + i * 126
        col = RED if i == 3 else INK
        b += R(x, 8, 116, 92, col) + T(x + 12, 36, str(i + 1), 20, "#9a9ca3" if i != 3 else "#ffd0d4", "start", "700")
        b += T(x + 12, 62, a, 13, "#fff", "start", "700") + T(x + 12, 82, c, 11, "#dcdde0")
        if i < 5:
            b += T(x + 121, 58, "›", 18, MUT, "middle")
    return fig(760, 108, b, "Шесть шагов проекта умного дома",
               "Шесть шагов: сценарии раньше железа, архитектура раньше протокола, электрика раньше отделки. Красным выделен шаг, который нельзя исправить дёшево после ремонта.")


def f_arch():
    b = ""
    # облако
    b += R(250, 8, 260, 40, "none", G1, 2).replace("<rect", '<rect stroke-dasharray="7 5"')
    b += T(380, 25, "облако: уведомления, удалённый доступ", 12, MUT, "middle") + T(380, 41, "необязательный слой", 11, G1, "middle")
    b += L(380, 48, 380, 96, G1, 2, "6 5")
    # датчики
    b += T(110, 82, "Датчики", 14, INK, "middle", "700")
    sens = ["присутствие, движение", "протечка", "CO₂, температура", "окна и двери"]
    for i, s in enumerate(sens):
        y = 96 + i * 50
        b += R(10, y, 200, 40, SOFT, INK, 2) + T(110, y + 25, s, 12, INK, "middle")
        b += arrow(210, y + 20, 290, 150 + (y - 96) * 0.25 + 10, INK, 2)
    # хаб
    b += R(290, 96, 180, 190, INK) + T(380, 128, "Локальный хаб", 15, "#fff", "middle", "700")
    b += T(380, 152, "сценарии и логика", 12, "#dcdde0", "middle") + T(380, 170, "работает без интернета", 12, "#dcdde0", "middle")
    b += R(306, 196, 148, 34, RED) + T(380, 218, "ИБП на хаб и сеть", 12, "#fff", "middle", "700")
    b += T(380, 258, "отклик 100–300 мс", 11, "#9a9ca3", "middle") + T(380, 274, "(ориентир практики)", 11, "#9a9ca3", "middle")
    # исполнители
    b += T(650, 82, "Исполнители", 14, INK, "middle", "700")
    acts = ["свет: реле, диммеры", "клапаны протечки", "климат: котёл, тепловой насос", "кондиционер, вентиляция"]
    for i, s in enumerate(acts):
        y = 96 + i * 50
        b += R(550, y, 200, 40, SOFT, INK, 2) + T(650, y + 25, s, 12, INK, "middle")
        b += arrow(470, 150 + (y - 96) * 0.25 + 10, 550, y + 20, INK, 2)
    # интерфейсы
    b += T(10, 316, "Управление:", 12, MUT, "start", "700")
    ui = [("кнопки и сцены", RED), ("панель и приложение", INK), ("голос", G1)]
    x = 100
    for s, col in ui:
        w = 24 + len(s) * 7
        b += R(x, 300, w, 22, col) + T(x + w / 2, 316, s, 11, "#fff", "middle", "700")
        x += w + 8
    b += T(750, 316, "первичное, вторичное, третье", 11, MUT, "end")
    return fig(760, 336, b, "Архитектура умного дома: локальный хаб и необязательное облако",
               "Датчики, хаб и исполнители работают локально. Облако даёт уведомления и удалённый доступ, но выключатели и климат от него не зависят. Питание ядра держит ИБП.")
