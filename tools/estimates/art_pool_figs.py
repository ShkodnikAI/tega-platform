"""Рисунки статьи «Бассейны»: чистый SVG без встроенных стилей и скриптов (CSP сайта их не пропускает).
Энергия посчитана по той же модели, что и калькулятор (static/pool-model.js): 30 м³, зеркало 20 м², +26 °C, 4 месяца, тепло на старт включено."""
from art_figs import T, R, L, PL, arrow, fig, INK, RED, MUT, G1, G2, G3, SOFT
from art_vent_figs import TH, ru

V, S, MONTHS, DT, COP, TARIFF = 30.0, 20.0, 4, 11.0, 4.5, 0.3037
E0 = V * 1.163 * DT


def season(k):
    return S * 0.25 * k * MONTHS * 720 + E0


CASES = [("ТЭН без покрытия", season(1.0), 1.0, G3), ("ТЭН, ламельное покрытие", season(0.45), 1.0, G1),
         ("Тепловой насос, ламельное покрытие", season(0.45), COP, INK), ("Тепловой насос, павильон и покрытие", season(0.35 * 0.45), COP, RED)]


def f_circuits():
    items = [("Циркуляция", "скиммеры, насос,", "фильтр, форсунки"), ("Водоподготовка", "обеззараживание, pH,", "прозрачность"), ("Тепло", "нагрев, покрытие,", "изоляция чаши"), ("Безопасность", "покрытие, ограждение,", "сигнализация")]
    b = ""
    for i, (a, c1, c2) in enumerate(items):
        x = 6 + i * 187
        col = RED if i == 2 else INK
        b += R(x, 18, 175, 96, col) + T(x + 87, 48, a, 14, "#fff", "middle", "700") + T(x + 87, 78, c1, 11, "#dcdde0", "middle") + T(x + 87, 94, c2, 11, "#dcdde0", "middle")
    b += T(6, 140, "Слабейший контур задаёт впечатление и счёт: мутная вода, электричество, конденсат или беда с детьми.", 12, MUT)
    return fig(760, 156, b, "Четыре контура бассейна", "Тип чаши и бюджет вторичны: сначала циркуляция, вода, тепло и безопасность.")


def f_circuit():
    names = ["Скиммер / перелив", "Префильтр", "Насос", "Фильтр", "Нагрев", "УФ / электролиз", "Дозатор pH и ORP", "Форсунки"]
    b = ""
    w, g = 82, 14
    for i, n in enumerate(names):
        x = 6 + i * (w + g)
        col = RED if n == "Нагрев" else INK
        b += R(x, 30, w, 54, col)
        words = n.replace(" / ", "/ ").split(" ")
        if len(words) == 1:
            b += T(x + w / 2, 62, n, 11, "#fff", "middle", "700")
        else:
            half = (len(words) + 1) // 2
            b += T(x + w / 2, 55, " ".join(words[:half]), 11, "#fff", "middle", "700") + T(x + w / 2, 71, " ".join(words[half:]), 11, "#fff", "middle", "700")
        if i < len(names) - 1:
            b += arrow(x + w + 1, 57, x + w + g - 1, 57, MUT, 2)
    b += L(6 + 3 * (w + g) + w / 2, 84, 6 + 3 * (w + g) + w / 2, 116, G1, 2, "6 4") + R(6 + 3 * (w + g) - 20, 116, w + 40, 30, SOFT, G2, 1) + T(6 + 3 * (w + g) + w / 2, 135, "Промывка в дренаж", 11, INK, "middle", "700")
    b += T(6, 172, "Промывка фильтра идёт мимо чаши, в свой дренаж или канализацию. Нагрев ставят после фильтра, дозирование после нагрева.", 12, MUT)
    return fig(760, 186, b, "Контур водоподготовки химического бассейна", "Порядок узлов: префильтр защищает насос, фильтр защищает нагрев, нагрев и дезинфекция стоят после фильтра.")


def f_energy():
    ox, oy = 250, 34
    mx = max(c[1] / c[2] for c in CASES)
    sc = 220.0 / mx
    b = T(6, 20, "Электричество на нагрев за сезон (30 м³, 20 м², +26 °C, 4 месяца)", 13, INK, "start", "700")
    for i, (nm, e, cop, col) in enumerate(CASES):
        el = e / cop
        y = oy + i * 46
        b += T(ox - 10, y + 22, nm, 12, INK, "end") + R(ox, y, max(2, el * sc), 30, col)
        b += T(ox + max(2, el * sc) + 8, y + 21, f"{ru(round(el, -1), 0)} кВт·ч, ≈ {ru(round(el * TARIFF, -1), 0)} BYN", 12, INK, "start", "700")
    b += T(6, oy + 4 * 46 + 8, f"COP теплового насоса {ru(COP, 1)} за сезон, тариф {ru(TARIFF, 4)} BYN/кВт·ч, потери открытой воды 0,25 кВт/м².", 11, MUT)
    return fig(760, oy + 4 * 46 + 30, b, "Сезонная энергия по вариантам нагрева", "Покрытие и тепловой насос дают порядок экономии против ТЭНа без покрытия. Оценка модели, а не замер: считайте свой бассейн в калькуляторе.")
