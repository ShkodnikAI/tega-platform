def viz_svg(card):
    v = card.get("viz")
    if not v:
        return ""
    k = v[0]
    if k == "classbars":
        return svg_classbars(v[1], v[2])
    if k == "classbars2":
        return svg_classbars(v[1], v[2], v[3], "Допуски облицовки")
    if k == "bars":
        return svg_bars(v[1], v[2])
    if k == "layers":
        return svg_layers()
    if k == "ops":
        return svg_ops()
    return ""


