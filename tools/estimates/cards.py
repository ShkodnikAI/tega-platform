# ───────────────────────── схемы SVG ─────────────────────────
def esc(s):
    return html.escape(str(s), quote=True)


def fnum(v):
    if isinstance(v, str):
        return v
    s = ("%g" % v).replace(".", ",")
    return s


def svg_open(w, h, label):
    return f'<svg viewBox="0 0 {w} {h}" role="img" aria-label="{esc(label)}" class="e-svg">'


def txt(x, y, s, size=14, fill=INK, anchor="start", weight=400, mono=False):
    fam = MONO if mono else FONT
    return f'<text x="{x}" y="{y}" font-size="{size}" fill="{fill}" text-anchor="{anchor}" font-weight="{weight}" font-family="{fam}">{esc(s)}</text>'


def svg_classbars(rows, unit, names=CLS, label="Допуски по классам"):
    w, left = 640, 190
    bw = w - left - 70
    out = []
    y = 34
    # легенда
    lx = left
    for i, nm in enumerate(names):
        col = (LIGHT, MID, INK)[i]
        out.append(f'<rect x="{lx}" y="12" width="12" height="12" fill="{col}"/>' + txt(lx + 18, 23, nm, 12, MID))
        lx += 24 + len(nm) * 7 + 18
    for lab, vals in rows:
        mx = max(vals)
        out.append(txt(0, y + 24, lab, 13))
        for i, v in enumerate(vals):
            col = (LIGHT, MID, INK)[i]
            ww = max(3, bw * v / mx)
            out.append(f'<rect x="{left}" y="{y + i * 15}" width="{ww:.1f}" height="11" fill="{col}"/>')
            out.append(txt(left + ww + 8, y + i * 15 + 10, f"{fnum(v)} {unit}", 11, INK, mono=True))
        y += 58
    return svg_open(w, y, label) + "".join(out) + "</svg>"


def svg_bars(rows, unit, label="Допуски"):
    w, left = 640, 220
    bw = w - left - 80
    mx = max(r[1] for r in rows)
    out, y = [], 6
    for lab, v in rows:
        out.append(txt(0, y + 16, lab, 13))
        ww = max(3, bw * v / mx)
        out.append(f'<rect x="{left}" y="{y}" width="{ww:.1f}" height="22" fill="{INK}"/>')
        out.append(txt(left + ww + 8, y + 16, f"{fnum(v)} {unit}", 12, RED, weight=500, mono=True))
        y += 34
    return svg_open(w, y + 4, label) + "".join(out) + "</svg>"


